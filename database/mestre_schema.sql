/* ==================================================================
   BANCO MESTRE - Gerenciador de Tarefas (multi-empresa)
   ==================================================================

   Este é um banco SEPARADO dos bancos de cada empresa. Ele só guarda
   duas coisas: a lista de empresas cadastradas (pra saber em qual
   banco conectar a partir do código digitado no login) e os usuários
   da equipe de suporte (que administram essas empresas).

   Crie o banco com charset UTF8:

   CREATE DATABASE 'C:\dados\MESTRE.FDB'
       USER 'SYSDBA' PASSWORD 'masterkey'
       PAGE_SIZE 16384
       DEFAULT CHARACTER SET UTF8;

   Depois conecte nesse banco e rode o restante deste arquivo.
   ================================================================== */


/* ----------------------------------------------------------------
   EMPRESAS
   - CODIGO: 6 caracteres, gerado pelo sistema (letras maiúsculas +
     números, sem O/0/I/1 pra evitar confusão visual). É o que a
     pessoa digita no login pra apontar pro banco certo.
   - CAMINHO_BANCO: caminho completo do arquivo .FDB dessa empresa.
   - ATIVA: permite suspender o acesso de uma empresa (ex: parou de
     pagar) sem apagar nada.
   ---------------------------------------------------------------- */
CREATE TABLE EMPRESAS (
    ID_EMPRESA       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME             VARCHAR(150) NOT NULL,
    CODIGO           VARCHAR(6) NOT NULL,
    CAMINHO_BANCO    VARCHAR(500) NOT NULL,
    ATIVA            SMALLINT DEFAULT 1 NOT NULL,
    DATA_CADASTRO    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

ALTER TABLE EMPRESAS ADD CONSTRAINT UK_EMPRESAS_CODIGO UNIQUE (CODIGO);


/* ----------------------------------------------------------------
   SUPORTE_USUARIOS
   - Login completamente separado dos usuários de empresa: só e-mail
     e senha, sem código de empresa, porque o suporte não pertence a
     nenhuma empresa - ele enxerga a lista inteira.
   ---------------------------------------------------------------- */
CREATE TABLE SUPORTE_USUARIOS (
    ID_SUPORTE_USUARIO   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME                 VARCHAR(100) NOT NULL,
    LOGIN                VARCHAR(100) NOT NULL,
    SENHA                VARCHAR(255) NOT NULL,
    ATIVO                SMALLINT DEFAULT 1 NOT NULL,
    DATA_CADASTRO        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

ALTER TABLE SUPORTE_USUARIOS ADD CONSTRAINT UK_SUPORTE_LOGIN UNIQUE (LOGIN);


