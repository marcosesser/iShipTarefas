/* ==================================================================
   MIGRAÇÃO: Arquivamento de tarefas + Histórico/Auditoria
   Rode este script no SEU banco já existente (não precisa recriar
   nada, só adiciona o que falta).
   ================================================================== */

/* Arquivamento: diferente de ATIVO (exclusão) - tarefa arquivada
   continua existindo e aparece nos relatórios, só some do board. */
ALTER TABLE TAREFA ADD ARQUIVADO SMALLINT DEFAULT 0 NOT NULL;
ALTER TABLE TAREFA ADD DATA_ARQUIVAMENTO TIMESTAMP;

COMMIT;

/* Auditoria automática: quem criou, quem moveu entre tags (e quando),
   quem arquivou/restaurou, quem editou. Gerada pelo backend, nunca
   editável pela tela. */
CREATE TABLE TAREFA_HISTORICO (
    ID_TAREFA_HISTORICO   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TAREFA             INTEGER NOT NULL,
    ID_USUARIO            INTEGER,
    ACAO                  VARCHAR(30) NOT NULL,
    DESCRICAO             VARCHAR(300) NOT NULL,
    VALOR_ANTERIOR        VARCHAR(200),
    VALOR_NOVO            VARCHAR(200),
    DATA_CADASTRO         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_TH_TAREFA FOREIGN KEY (ID_TAREFA) REFERENCES TAREFA (ID_TAREFA),
    CONSTRAINT FK_TH_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIO)
);

CREATE INDEX IDX_HISTORICO_TAREFA ON TAREFA_HISTORICO (ID_TAREFA);

COMMIT;
