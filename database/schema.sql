/* ==================================================================
   GERENCIADOR DE TAREFAS - ESTRUTURA DO BANCO (FIREBIRD 3.0+)
   ==================================================================

   Antes de rodar este script, crie o banco com charset UTF8
   (necessário para acentuação em português):

   CREATE DATABASE 'C:\dados\GERENCIADOR_TAREFAS.FDB'
       USER 'SYSDBA' PASSWORD 'masterkey'
       PAGE_SIZE 16384
       DEFAULT CHARACTER SET UTF8;

   Depois conecte nesse banco e rode o restante deste arquivo.
   ================================================================== */


/* ----------------------------------------------------------------
   USUARIOS
   - ID_USUARIO gerado automaticamente (IDENTITY = generator/trigger
     nativo do Firebird 3+, equivalente ao GENERATOR manual).
   - LOGIN é UNIQUE porque é o e-mail usado no login.
   - SENHA guarda o HASH (bcrypt via password_hash do PHP), nunca a
     senha em texto puro.
   - ATIVO permite inativar usuário sem apagar o histórico dele
     (soft delete), já que ele pode estar referenciado em tarefas.
   ---------------------------------------------------------------- */
CREATE TABLE USUARIOS (
    ID_USUARIO      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME            VARCHAR(100) NOT NULL,
    LOGIN           VARCHAR(100) NOT NULL,
    SENHA           VARCHAR(255) NOT NULL,
    ATIVO           SMALLINT DEFAULT 1 NOT NULL,
    DATA_CADASTRO   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

ALTER TABLE USUARIOS ADD CONSTRAINT UK_USUARIOS_LOGIN UNIQUE (LOGIN);


/* ----------------------------------------------------------------
   TAG
   - ORDEM é UNIQUE: é exatamente a validação que você pediu (não
     pode cadastrar duas tags com a mesma posição na tela inicial).
   ---------------------------------------------------------------- */
CREATE TABLE TAG (
    ID_TAG          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRICAO       VARCHAR(100) NOT NULL,
    ORDEM           INTEGER NOT NULL,
    ATIVO           SMALLINT DEFAULT 1 NOT NULL,
    DATA_CADASTRO   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

ALTER TABLE TAG ADD CONSTRAINT UK_TAG_ORDEM UNIQUE (ORDEM);


/* ----------------------------------------------------------------
   TAREFA
   - ORDEM: posição do card dentro da coluna/TAG. Não estava no seu
     desenho original, mas é necessária para guardar a ordem em que
     os cards ficam dentro de cada coluna depois do arrasta-e-solta.
   - ID_USUARIO_CADASTRO: quem criou a tarefa (usado no relatório e
     para saber o autor do card).
   - ARQUIVADO: diferente de ATIVO (que é exclusão/soft-delete) -
     uma tarefa arquivada continua existindo e aparece nos relatórios,
     só some do board. Pode ser restaurada a qualquer momento.
   ---------------------------------------------------------------- */
CREATE TABLE TAREFA (
    ID_TAREFA             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TAG                INTEGER NOT NULL,
    DESCRICAO             VARCHAR(200) NOT NULL,
    OBSERVACAO            BLOB SUB_TYPE TEXT,
    ORDEM                 INTEGER DEFAULT 0 NOT NULL,
    ID_USUARIO_CADASTRO   INTEGER,
    DATA_CADASTRO         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO                 SMALLINT DEFAULT 1 NOT NULL,
    ARQUIVADO             SMALLINT DEFAULT 0 NOT NULL,
    DATA_ARQUIVAMENTO     TIMESTAMP,
    CONSTRAINT FK_TAREFA_TAG FOREIGN KEY (ID_TAG) REFERENCES TAG (ID_TAG),
    CONSTRAINT FK_TAREFA_USUARIO FOREIGN KEY (ID_USUARIO_CADASTRO) REFERENCES USUARIOS (ID_USUARIO)
);

CREATE INDEX IDX_TAREFA_TAG ON TAREFA (ID_TAG);


/* ----------------------------------------------------------------
   TAREFA_USUARIOS
   - Vínculo N:N entre tarefa e usuário. Regra de visibilidade
     aplicada no backend (ver api/tarefas.php):
       * tarefa SEM nenhum usuário vinculado -> visível para todos
       * tarefa COM usuários vinculados -> visível só para eles
   ---------------------------------------------------------------- */
CREATE TABLE TAREFA_USUARIOS (
    ID_TAREFA_USUARIOS   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TAREFA            INTEGER NOT NULL,
    ID_USUARIOS           INTEGER NOT NULL,
    CONSTRAINT FK_TU_TAREFA FOREIGN KEY (ID_TAREFA) REFERENCES TAREFA (ID_TAREFA),
    CONSTRAINT FK_TU_USUARIO FOREIGN KEY (ID_USUARIOS) REFERENCES USUARIOS (ID_USUARIO)
);

ALTER TABLE TAREFA_USUARIOS ADD CONSTRAINT UK_TAREFA_USUARIO UNIQUE (ID_TAREFA, ID_USUARIOS);


/* ----------------------------------------------------------------
   TAREFA_ANEXO
   - ANEXO guarda o CAMINHO do arquivo em disco (ex: uploads/tarefas/
     xyz.pdf), não o binário em BLOB. É mais leve pro Firebird e mais
     simples de servir depois pelo PHP/Apache.
   ---------------------------------------------------------------- */
CREATE TABLE TAREFA_ANEXO (
    ID_TAREFA_ANEXO   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TAREFA         INTEGER NOT NULL,
    DESCRICAO         VARCHAR(200),
    ANEXO             VARCHAR(500) NOT NULL,
    DATA_CADASTRO     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_TA_TAREFA FOREIGN KEY (ID_TAREFA) REFERENCES TAREFA (ID_TAREFA)
);


/* ----------------------------------------------------------------
   TAREFA_EVENTOS
   - Anotações/comentários que o próprio usuário digita na tarefa
     (equivalente aos comentários de um card no Trello). Totalmente
     editável/apagável pelo usuário - para o registro AUTOMÁTICO e
     imutável do sistema (quem criou, quem moveu entre tags, etc.),
     veja TAREFA_HISTORICO logo abaixo.
   ---------------------------------------------------------------- */
CREATE TABLE TAREFA_EVENTOS (
    ID_TAREFA_EVENTOS   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TAREFA           INTEGER NOT NULL,
    DESCRICAO           VARCHAR(200) NOT NULL,
    OBSERVACAO          BLOB SUB_TYPE TEXT,
    ID_USUARIO          INTEGER,
    DATA_CADASTRO       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_TE_TAREFA FOREIGN KEY (ID_TAREFA) REFERENCES TAREFA (ID_TAREFA),
    CONSTRAINT FK_TE_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIO)
);


/* ----------------------------------------------------------------
   TAREFA_EVENTOS_ANEXO
   ---------------------------------------------------------------- */
CREATE TABLE TAREFA_EVENTOS_ANEXO (
    ID_TAREFA_EVENTOS_ANEXO   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TAREFA_EVENTOS         INTEGER NOT NULL,
    DESCRICAO                 VARCHAR(200),
    ANEXO                     VARCHAR(500) NOT NULL,
    DATA_CADASTRO             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_TEA_EVENTO FOREIGN KEY (ID_TAREFA_EVENTOS) REFERENCES TAREFA_EVENTOS (ID_TAREFA_EVENTOS)
);


/* ----------------------------------------------------------------
   TAREFA_HISTORICO
   - Auditoria AUTOMÁTICA gerada pelo backend, nunca editável pela
     tela: quem criou a tarefa, quem moveu entre tags (e quando),
     quem arquivou/restaurou, quem editou descrição/observação.
   - ACAO é um código curto (CRIACAO, MOVIMENTACAO, EDICAO,
     ARQUIVAMENTO, RESTAURACAO) usado para escolher o ícone na tela.
   - VALOR_ANTERIOR/VALOR_NOVO guardam um resumo textual da mudança
     (ex: nome da tag antiga/nova), quando fizer sentido para a ação.
   ---------------------------------------------------------------- */
CREATE TABLE TAREFA_HISTORICO (
    ID_TAREFA_HISTORICO   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TAREFA             INTEGER NOT NULL,
    ID_USUARIO            INTEGER,
    ACAO                  VARCHAR(30) NOT NULL,
    DESCRICAO             VARCHAR(300) NOT NULL,
    VALOR_ANTERIOR        VARCHAR(200),
    VALOR_NOVO            VARCHAR(200),
    DATA_CADASTRO         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_TH_TAREFA FOREIGN KEY (ID_TAREFA) REFERENCES TAREFA (ID_TAREFA),
    CONSTRAINT FK_TH_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIO)
);

CREATE INDEX IDX_HISTORICO_TAREFA ON TAREFA_HISTORICO (ID_TAREFA);


